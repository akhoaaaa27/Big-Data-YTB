# Credits must describe this work rather than the channel's catalogue.
WORK_CREDIT = re.compile(
    r"^\W*(?:ai cover\s*(?:[•|:]|by\b)|"
    r"(?:nhac(?: va ca si)?|am nhac|ca si|trinh bay|giong hat|giong ca|sang tac|hoa am|phoi khi|"
    r"the hien|music|song|vocals?|voice|producer|vocalist)\s*[:：-])"
    r"|\b(?:bai hat nay|ca khuc nay|video nay|ban nhac nay|this (?:song|track|video)|"
    r"duoc tao|tao bang|tao boi|generated by|created with|produced with)\b"
)


def classify_video(video):
    """Apply stricter per-work credits without changing the original classifier."""
    original = classify(video)
    if original[0] != "include":
        # Preserve denials, category exclusions and other original safeguards.
        return original
    description = normalize(video.get("description"))
    channel = normalize(video.get("channel_title"))
    if len(channel) >= 6:
        description = description.replace(channel, " ")
    checked = dict(video)
    checked["description"] = "\n".join(line for line in description.splitlines() if WORK_CREDIT.search(line))
    return classify(checked)


def _write_csv(path, rows):
    # The entire output directory is published atomically by prepare_inputs.
    with path.open("w", encoding="utf-8-sig", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


class CommentLanguage:
    """Offline language detection; ambiguous/short text is explicitly unknown."""

    def __init__(self, confidence=0.8, margin=0.15):
        from lingua import LanguageDetectorBuilder
        self.detector = LanguageDetectorBuilder.from_all_spoken_languages().build()
        self.confidence = confidence
        self.margin = margin

    @lru_cache(maxsize=100000)
    def __call__(self, text):
        text = re.sub(r"https?://\S+|www\.\S+", " ", html.unescape(text or ""))
        words = re.findall(r"[^\W\d_]+", text, flags=re.UNICODE)
        if len(words) < 3 or sum(map(len, words)) < 12:
            return "und", 0.0, 0.0, "short"
        values = self.detector.compute_language_confidence_values(text)
        if not values:
            return "und", 0.0, 0.0, "uncertain"
        best = values[0]
        margin = best.value - (values[1].value if len(values) > 1 else 0)
        code = best.language.iso_code_639_1.name.lower()
        status = ("vi" if code == "vi" else "other") if best.value >= self.confidence and margin >= self.margin else "uncertain"
        return code, float(best.value), float(margin), status


def _fingerprint(source):
    """Hash every original Parquet file so the trial can verify source preservation."""
    digest = hashlib.sha256()
    for file in sorted(source.rglob("*.parquet")):
        digest.update(str(file.relative_to(source)).encode())
        with file.open("rb") as stream:
            for block in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(block)
    return digest.hexdigest()


def _concentration(rows):
    counts = sorted(Counter(r["video_id"] for r in rows).values(), reverse=True)
    return {"comments": len(rows), "videos": len(counts),
            "top_video_fraction": counts[0] / len(rows) if rows else 0,
            "top_10_video_fraction": sum(counts[:10]) / len(rows) if rows else 0}


def prepare_inputs(source=None, output=None, cap_per_video=50,
                   confidence=0.8, margin=0.15, detector=None):
    """Build a reversible trial, without replacing Core, curated or model results.

    AI audio and Vietnamese scope are metadata claims, not audio verification or
    proof that production took place in Vietnam. Unknown language stays in audit.
    """
    source = Path(source or config.DATA_DIR / "core").resolve()
    output = Path(output or config.DATA_DIR / "filtered_comments").absolute()
    resolved = output.resolve()
    if resolved == source or source in resolved.parents or resolved in source.parents:
        raise ValueError("Thư mục xuất phải tách biệt với nguồn")
    if output.exists() or output.is_symlink():
        raise ValueError(f"Không ghi đè thư mục đã có: {output}")
    if cap_per_video < 1 or not 0 < confidence <= 1 or not 0 <= margin <= 1:
        raise ValueError("cap >= 1; confidence trong (0, 1]; margin trong [0, 1]")
    before_hash = _fingerprint(source)
    videos = ds.dataset(source / "videos", format="parquet").to_table()
    comments = ds.dataset(source / "comments", format="parquet").to_table()
    video_rows, rows = videos.to_pylist(), comments.to_pylist()
    for records, column in ((video_rows, "video_id"), (rows, "comment_id")):
        ids = [r[column] for r in records]
        if any(not value for value in ids) or len(ids) != len(set(ids)):
            raise ValueError(f"{column} phải duy nhất, không rỗng")
    required = {"video_id", "text_raw", "text_clean", "tokens", "is_reply", "is_modelable"}
    if required - set(comments.column_names):
        raise ValueError(f"Thiếu cột: {sorted(required - set(comments.column_names))}")
    language = detector if detector is not None else CommentLanguage(confidence, margin)
    counts = Counter(r["video_id"] for r in rows)
    decisions, accepted = [], set()
    for video in video_rows:
        decision, reason, evidence = classify_video(video)
        if decision == "include":
            declared = str(video.get("default_audio_language") or "").lower().split("-")[0]
            # A declared foreign audio language takes precedence over translated text.
            vi_metadata = declared == "vi"
            if not declared:
                vi_metadata = any(language(str(video.get(field) or "")[:1000])[3] == "vi"
                                  for field in ("title", "description"))
            if not vi_metadata:
                decision, reason = "uncertain", "Có dấu hiệu nhạc AI nhưng chưa đủ metadata tiếng Việt"
            else:
                reason += "; có metadata tiếng Việt (chưa xác minh âm thanh/nơi sản xuất)"
        vid = video["video_id"]
        if decision == "include":
            accepted.add(vid)
        decisions.append(dict(video_id=vid, url=f"https://www.youtube.com/watch?v={vid}",
                              title=video.get("title") or "", channel_title=video.get("channel_title") or "",
                              n_comments=counts[vid], decision=decision, reason=reason, evidence=evidence))
    audit = []
    for row in rows:
        raw = html.unescape(str(row.get("text_raw") or "")).strip()
        if row["video_id"] not in accepted:
            code, score, gap, status = "und", 0.0, 0.0, "not_checked"
            sentiment_reason = "video_not_accepted"
        else:
            code, score, gap, status = language(raw)
            # Only quarantine URLs with explicit sales/scam solicitation; names,
            # greetings, profanity and ordinary links are not spam by themselves.
            spam = bool(re.search(r"https?://|www\.", raw, re.I) and re.search(
                r"\b(?:mua ngay|dat hang|lien he mua|kiem tien|nhan thuong|casino|ca cuoc|buy now|earn money)\b", normalize(raw)))
            sentiment_reason = ("empty_text" if not raw else "suspected_link_spam" if spam
                                else "language_other" if status == "other"
                                else "language_uncertain" if status == "uncertain" else "keep")
        topic_reason = sentiment_reason
        if sentiment_reason == "keep":
            topic_reason = ("language_short" if status != "vi" else "not_modelable" if not row["is_modelable"]
                            else "reply" if row["is_reply"] else "too_few_tokens" if len(row["tokens"] or []) < 2 else "keep")
        audit.append(dict(comment_language=code, comment_language_confidence=score,
                          comment_language_margin=gap, comment_language_status=status,
                          sentiment_reason=sentiment_reason, topic_reason=topic_reason))
    # Stable hash sampling avoids dependence on Parquet partition order.
    candidates = sorted((i for i, a in enumerate(audit) if a["topic_reason"] == "keep"),
                        key=lambda i: str(rows[i]["comment_id"]))
    seen, unique = set(), []
    for i in candidates:
        key = str(rows[i]["text_clean"] or "").casefold().strip()
        if not key:
            audit[i]["topic_reason"] = "empty_clean_text"
        elif key in seen:
            audit[i]["topic_reason"] = "duplicate_text"
        else:
            seen.add(key)
            unique.append(i)
    before_cap = _concentration([rows[i] for i in unique])
    per_video = Counter()
    for i in sorted(unique, key=lambda i: hashlib.sha256(("0:" + str(rows[i]["comment_id"])).encode()).digest()):
        vid = rows[i]["video_id"]
        if per_video[vid] >= cap_per_video:
            audit[i]["topic_reason"] = "video_cap"
        else:
            per_video[vid] += 1
    topic_indices = [i for i, a in enumerate(audit) if a["topic_reason"] == "keep"]
    sentiment_indices = [i for i, a in enumerate(audit) if a["sentiment_reason"] == "keep"]
    enriched = comments.replace_schema_metadata(None)
    types = {"comment_language": pa.string(), "comment_language_confidence": pa.float64(),
             "comment_language_margin": pa.float64(), "comment_language_status": pa.string(),
             "sentiment_reason": pa.string(), "topic_reason": pa.string()}
    for name, dtype in types.items():
        if name in enriched.column_names:
            raise ValueError(f"Nguồn đã có cột thử nghiệm {name}; hãy dùng Core")
        enriched = enriched.append_column(name, pa.array([a[name] for a in audit], type=dtype))
    summary = dict(method="metadata_and_language_trial_v1", source=str(source), output=str(output),
                   generated_at=datetime.now(timezone.utc).isoformat(),
                   production_location_verified=False, audio_verified=False,
                   language_detector="lingua-language-detector==2.1.1/all_spoken_languages" if detector is None else "injected",
                   confidence_threshold=confidence, margin_threshold=margin, topic_cap_per_video=cap_per_video,
                   sampling="sha256(0:comment_id)", input_videos=len(video_rows), input_comments=len(rows),
                   video_decisions=dict(Counter(r["decision"] for r in decisions)),
                   video_accepted_comments=sum(r["video_id"] in accepted for r in rows),
                   sentiment_comments=len(sentiment_indices), topic_comments=len(topic_indices),
                   sentiment_reasons=dict(Counter(a["sentiment_reason"] for a in audit)),
                   topic_reasons=dict(Counter(a["topic_reason"] for a in audit)),
                   language_statuses=dict(Counter(a["comment_language_status"] for a in audit)),
                   before_topic_cap=before_cap, after_topic_cap=_concentration([rows[i] for i in topic_indices]))
    output.parent.mkdir(parents=True, exist_ok=True)
    temp = Path(tempfile.mkdtemp(prefix=".analysis-trial-", dir=output.parent))
    try:
        for name, indices in (("topics", topic_indices), ("sentiment", sentiment_indices)):
            folder = temp / name / "comments"
            folder.mkdir(parents=True)
            pq.write_table(enriched.take(pa.array(indices, type=pa.int64())), folder / "part-00000.parquet", compression="zstd")
        pq.write_table(enriched, temp / "comments_audit.parquet", compression="zstd")
        for name in ("videos", "video_snapshots"):
            if not (source / name).exists():
                continue
            table = videos if name == "videos" else ds.dataset(source / name, format="parquet").to_table()
            folder = temp / name
            folder.mkdir()
            pq.write_table(table.filter(pc.is_in(table["video_id"], value_set=pa.array(sorted(accepted), type=pa.string()))),
                           folder / "part-00000.parquet", compression="zstd")
        _write_csv(temp / "video_decisions.csv", decisions)
        summary["source_sha256_before"] = before_hash
        summary["source_sha256_after"] = _fingerprint(source)
        if summary["source_sha256_after"] != before_hash:
            raise ValueError("Nguồn thay đổi trong lúc chạy; không công bố kết quả thử")
        (temp / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
        if output.exists() or output.is_symlink():
            raise ValueError("Thư mục xuất vừa được tạo bởi tiến trình khác")
        temp.rename(output)
    finally:
        if temp.exists():
            shutil.rmtree(temp)
    return summary


def compare_sources(comments, real_videos, synthetic_videos, output, *,
                    cap_per_video=50, confidence=0.8, margin=0.15,
                    detector=None, train_models=False, seed=42, iterations=30):
    """Filter a mixed input and compare origins without expanding Core columns.

    Real video membership uses original metadata; synthetic metadata is only a
    test fixture. Language decisions stay in a sidecar, never Core columns.
    """
    comments, real_videos, synthetic_videos, output = map(
        Path, (comments, real_videos, synthetic_videos, output))
    target = output.resolve()
    core = (config.DATA_DIR / "core").resolve()
    if target == core or core in target.parents or target in core.parents:
        raise ValueError("Đầu ra phải tách biệt với Core")
    for source in (comments.resolve(), real_videos.resolve(), synthetic_videos.resolve()):
        if target == source or target in source.parents or source in target.parents:
            raise ValueError("Đầu ra phải tách biệt với các nguồn")
    if output.exists() or output.is_symlink():
        raise FileExistsError(f"Không ghi đè: {output}")
    if seed < 0 or iterations < 1:
        raise ValueError("seed >= 0 và iterations >= 1")
    if cap_per_video < 1 or not 0 < confidence <= 1 or not 0 <= margin <= 1:
        raise ValueError("cap >= 1; confidence trong (0, 1]; margin trong [0, 1]")
    input_hash = hashlib.sha256(comments.read_bytes()).hexdigest()
    table = pq.read_table(comments)
    if len(table.column_names) != 18 or "source" not in table.column_names:
        raise ValueError("Cần bảng bình luận Core đúng 18 cột, có source")
    if set(table["source"].to_pylist()) - {"api", "legacy_csv", "synthetic"}:
        raise ValueError("source phải là api, legacy_csv hoặc synthetic")
    if len(set(table["comment_id"].to_pylist())) != table.num_rows:
        raise ValueError("comment_id phải duy nhất trong bản ghép")
    language = detector if detector is not None else CommentLanguage(confidence, margin)
    summary = dict(input=str(comments.resolve()), input_rows=table.num_rows,
                   input_sha256_before=input_hash, core_columns=table.column_names,
                   language_confidence=confidence, language_margin=margin,
                   cap_per_video=cap_per_video, origins={}, models={},
                   model_parameters=dict(k=20, alpha=.1, beta=.1, seed=seed,
                                         iterations=iterations, min_word_freq=2),
                   production_location_verified=False, audio_verified=False,
                   limitation="Metadata-only selection; synthetic models are diagnostic, not evidence about real audiences.")
    output.parent.mkdir(parents=True, exist_ok=True)
    temp = Path(tempfile.mkdtemp(prefix=".source-comparison-", dir=output.parent))
    try:
        for origin, metadata_path in (("real", real_videos), ("synthetic", synthetic_videos)):
            mask = pc.equal(table["source"], "synthetic")
            if origin == "real":
                mask = pc.invert(mask)
            subset = table.filter(mask)
            if not subset.num_rows:
                raise ValueError(f"Không có dòng thuộc nguồn {origin}")
            videos = ds.dataset(metadata_path, format="parquet").to_table()
            relevant_ids = pc.unique(subset["video_id"])
            videos = videos.filter(pc.is_in(videos["video_id"], value_set=relevant_ids))
            missing = set(relevant_ids.to_pylist()) - set(videos["video_id"].to_pylist())
            staged = temp / "_inputs" / origin
            (staged / "comments").mkdir(parents=True)
            (staged / "videos").mkdir()
            pq.write_table(subset, staged / "comments/part-00000.parquet", compression="zstd")
            pq.write_table(videos, staged / "videos/part-00000.parquet", compression="zstd")
            print(f"Lọc nguồn {origin}: {subset.num_rows:,} bình luận, {videos.num_rows:,} video", flush=True)
            prepared = temp / origin
            details = prepare_inputs(staged, prepared, cap_per_video, confidence, margin, language)
            for kind in ("topics", "sentiment"):
                path = prepared / kind / "comments/part-00000.parquet"
                clean = pq.read_table(path).select(table.column_names).cast(table.schema)
                pq.write_table(clean, path, compression="zstd")
                # CSV mirrors the same 18-column Parquet; reports are separate.
                csv_path = prepared / kind / "comments.csv"
                with csv_path.open("w", encoding="utf-8-sig", newline="") as stream:
                    writer = csv.DictWriter(stream, fieldnames=table.column_names, lineterminator="\n")
                    writer.writeheader()
                    for row in clean.to_pylist():
                        writer.writerow({key: json.dumps(value, ensure_ascii=False) if isinstance(value, list)
                                         else value.isoformat() if hasattr(value, "isoformat") else value
                                         for key, value in row.items()})
            audit_path = prepared / "comments_audit.parquet"
            audit = pq.read_table(audit_path)
            report_columns = ["comment_id", "video_id"] + [name for name in audit.column_names if name not in table.column_names]
            pq.write_table(audit.select(report_columns), audit_path, compression="zstd")
            details["source"] = str(comments.resolve())
            details["output"] = str(output.resolve() / origin)
            details["metadata_source"] = str(metadata_path.resolve())
            details["origin"] = origin
            details["metadata_is_synthetic_fixture"] = origin == "synthetic"
            details["missing_video_metadata"] = len(missing)
            details["staged_input_sha256_before"] = details.pop("source_sha256_before")
            details["staged_input_sha256_after"] = details.pop("source_sha256_after")
            details["language_detector"] = "injected" if detector is not None else "lingua-language-detector==2.1.1/all_spoken_languages"
            (prepared / "summary.json").write_text(json.dumps(details, ensure_ascii=False, indent=2), encoding="utf-8")
            summary["origins"][origin] = details
            print(f"{origin}: {details['topic_comments']:,} dòng cho GSDMM; {details['sentiment_comments']:,} cho sentiment", flush=True)
        shutil.rmtree(temp / "_inputs")
        del language
        if train_models:
            from .modeling.train_topics import train
            for origin in ("real", "synthetic"):
                source = temp / origin / "topics/comments"
                model_dir = temp / origin / "gsdmm" / f"seed_{seed}"
                if not summary["origins"][origin]["topic_comments"]:
                    summary["models"][origin] = {"status": "skipped_empty_input"}
                    continue
                print(f"GSDMM {origin}: K=20, seed={seed}, {iterations} vòng; ngôn ngữ đã lọc ở bước trước", flush=True)
                # Explicitly bypass the legacy accent heuristic on 18-column
                # inputs already checked by Lingua, including unaccented VI.
                try:
                    model = train(source, model_dir, seed=seed, iterations=iterations, vi_filter=False)
                except ValueError as error:
                    if not str(error).startswith("Không còn bình luận đủ điều kiện huấn luyện"):
                        raise
                    summary["models"][origin] = {"status": "skipped_empty_after_vocabulary_filter", "reason": str(error)}
                    continue
                examples = _topic_examples(model_dir)
                summary["models"][origin] = {**model, "status": "completed",
                                             "upstream_language_filter": "Lingua VI confidence/margin",
                                             "topic_examples": examples}
        summary["input_sha256_after"] = hashlib.sha256(comments.read_bytes()).hexdigest()
        if summary["input_sha256_after"] != input_hash:
            raise ValueError("Bản ghép đầu vào thay đổi trong lúc chạy")
        # Paths in published summaries must refer to the final directory.
        for model in summary["models"].values():
            if "source" in model:
                model["source"] = str(output.resolve() / Path(model["source"]).relative_to(temp.resolve()))
        for origin in summary["models"]:
            summary_file = temp / origin / "gsdmm" / f"seed_{seed}" / "training_summary.json"
            if summary_file.exists():
                model_summary = json.loads(summary_file.read_text())
                model_summary["source"] = str(output.resolve() / origin / "topics/comments")
                model_summary["upstream_language_filter"] = "Lingua VI confidence/margin; see origin summary and audit"
                summary_file.write_text(json.dumps(model_summary, ensure_ascii=False, indent=2), encoding="utf-8")
        (temp / "comparison.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
        (temp / "README.md").write_text(
            "# Đối chiếu GSDMM: dữ liệu thật và giả lập\n\n"
            "Hai nhóm được lọc và huấn luyện riêng; không trộn để làm kết luận về người xem thật. "
            "Nhóm thật xét metadata video gốc; nhóm giả lập dùng metadata giả lập làm đối chứng. "
            "Không xác minh âm thanh hoặc nơi sản xuất tại Việt Nam chỉ bằng metadata.\n\n"
            "real/ và synthetic/ có topics/comments/part-00000.parquet và sentiment/comments/part-00000.parquet: "
            "các bảng bình luận đều đúng 18 cột Core, không thêm cờ/nhãn và không sửa giá trị giữ lại. "
            "Sentiment giữ câu ngắn/emoji và reply; GSDMM chỉ lấy tiếng Việt đủ ngưỡng, modelable, không reply, "
            "khử trùng và giới hạn 50 dòng/video mặc định.\n\n"
            "comments_audit.parquet chứa ID và lý do giữ/loại; đây là báo cáo riêng, không phải bảng Core. "
            "video_decisions.csv ghi bằng chứng metadata. comparison.json ghi toàn bộ tham số, số dòng và kết quả.\n\n"
            "GSDMM dùng K=20, alpha=beta=0.1, seed 42, 30 vòng mặc định cho cả hai nhóm. "
            "Tắt heuristic dấu tiếng Việt trong train vì Lingua đã lọc ở bước trước. "
            "Đầu ra model có thêm cột cluster/text_gsdmm theo chức năng mô hình. "
            "topic_examples.json dùng ví dụ ngẫu nhiên có seed, không gọi đó là ví dụ có độ tin cậy cao nhất.\n\n"
            "Số dòng sau lọc có thể nhỏ. Các trường hợp không chắc được giữ trong audit, không khẳng định "
            "mọi dòng bị loại đều sai chủ đề hoặc sai ngôn ngữ. Các nguồn, bản ghép cũ và curate.py giữ nguyên.\n",
            encoding="utf-8")
        if output.exists() or output.is_symlink():
            raise FileExistsError(output)
        temp.rename(output)
    finally:
        if temp.exists():
            shutil.rmtree(temp)
    return summary


def _topic_examples(model_dir):
    rows = pq.read_table(model_dir / "comments_clustered.parquet").to_pylist()
    with (model_dir / "cluster_top_words.csv").open(encoding="utf-8-sig") as stream:
        words = list(csv.DictReader(stream))
    examples = []
    for item in words:
        cluster = int(item["cluster"])
        members = sorted((r for r in rows if r["cluster"] == cluster), key=lambda r: r["comment_id"])
        sample = random.Random(42 + cluster).sample(members, min(5, len(members)))
        examples.append(dict(cluster=cluster, comments=len(members), top_words=item["top_words"],
                             random_examples=[{key: r[key] for key in ("comment_id", "video_id", "text_raw")} for r in sample]))
    (model_dir / "topic_examples.json").write_text(json.dumps(examples, ensure_ascii=False, indent=2), encoding="utf-8")
    return examples



def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source-dir", type=Path, default=config.DATA_DIR / "core")
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--compare-sources", action="store_true", help="Lọc và đối chiếu riêng thật/giả, bảng bình luận 18 cột")
    parser.add_argument("--comments-file", type=Path, default=config.DATA_DIR / "mixed_comments_73247_v2/comments.parquet")
    parser.add_argument("--real-videos-dir", type=Path, default=config.DATA_DIR / "core/videos")
    parser.add_argument("--synthetic-videos-dir", type=Path, default=config.DATA_DIR / "synthetic_comments_50000/videos")
    parser.add_argument("--cap-per-video", type=int, default=50)
    parser.add_argument("--language-confidence", type=float, default=0.8)
    parser.add_argument("--language-margin", type=float, default=0.15)
    parser.add_argument("--train", action="store_true", help="Chạy GSDMM với chính Parquet vừa lọc")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--iterations", type=int, default=30)
    args = parser.parse_args(argv)
    if args.seed < 0 or args.iterations < 1:
        parser.error("seed phải >= 0; iterations phải >= 1")
    output = args.output_dir or config.DATA_DIR / ("source_comparison" if args.compare_sources else "filtered_comments")
    if args.compare_sources:
        try:
            result = compare_sources(args.comments_file, args.real_videos_dir, args.synthetic_videos_dir, output,
                                     cap_per_video=args.cap_per_video, confidence=args.language_confidence,
                                     margin=args.language_margin, train_models=args.train,
                                     seed=args.seed, iterations=args.iterations)
        except (ValueError, FileExistsError, FileNotFoundError) as error:
            parser.exit(1, f"Lỗi đối chiếu: {error}\n")
        print(json.dumps({key: value for key, value in result.items() if key not in ("origins", "models")}, ensure_ascii=False, indent=2))
        return
    try:
        result = prepare_inputs(args.source_dir, output, args.cap_per_video,
                                args.language_confidence, args.language_margin)
    except (ValueError, FileExistsError, FileNotFoundError) as error:
        parser.exit(1, f"Lỗi lọc: {error}\n")
    print(json.dumps(result, ensure_ascii=False, indent=2), flush=True)
    if args.train:
        from .modeling.train_topics import train
        source = output / "topics" / "comments"
        target = output / "gsdmm" / f"seed_{args.seed}"
        try:
            trained = train(source, target, seed=args.seed, iterations=args.iterations)
        except (ValueError, FileExistsError, FileNotFoundError) as error:
            parser.exit(1, f"Đã lưu dữ liệu lọc ở {output}; GSDMM chưa hoàn tất: {error}\n")
        print(json.dumps({**trained, "output": str(target)}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
